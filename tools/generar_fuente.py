def con(base, marcas):
    """Copia el glifo base y le suma píxeles (columna, fila)."""
    g = list(ASCII[base])
    for col, bit in marcas:
        g[col] |= 1 << bit
    return g


def voltear(g):
    """Espejo vertical de las 7 filas (para ¿ y ¡)."""
    salida = []
    for c in g:
        v = 0
        for b in range(7):
            if c & (1 << b):
                v |= 1 << (6 - b)
        salida.append(v)
    return salida


AGUDO = [(2, 1), (3, 0)]  # acento agudo en las filas 0-1 (las minúsculas ocupan las filas 2-6)

EXTRAS = {
    0xE1: ('á', con('a', AGUDO)),
    0xE9: ('é', con('e', AGUDO)),
    0xF3: ('ó', con('o', AGUDO)),
    0xFA: ('ú', con('u', AGUDO)),
    0xED: ('í', [0x00, 0x44, 0x7C | 0x02, 0x40 | 0x01, 0x00]),  # 'i' sin punto + acento
    0xF1: ('ñ', con('n', [(0, 1), (1, 0), (2, 0), (3, 1)])),
    0xFC: ('ü', con('u', [(1, 0), (3, 0)])),
    0xBF: ('¿', voltear(ASCII['?'])),
    0xA1: ('¡', voltear(ASCII['!'])),
    0xB0: ('°', [0x00, 0x06, 0x09, 0x09, 0x06]),
}


def glifo(ch):
    if ord(ch) in EXTRAS:
        return EXTRAS[ord(ch)][1]
    return ASCII.get(ch, ASCII['?'])


def dibujar(texto):
    for fila in range(7):
        print("  " + "  ".join(
            "".join("#" if glifo(c)[col] & (1 << fila) else "." for col in range(5)) for c in texto))


def main():
    if '--ver' in sys.argv:
        dibujar(sys.argv[sys.argv.index('--ver') + 1])
        return

    print("Verificación visual de los glifos:\n")
    for linea in ("ABCDEFGHIJKLM", "NOPQRSTUVWXYZ", "abcdefghijklm", "nopqrstuvwxyz",
                  "0123456789", "áéíóú ñ ü ¿?¡! °%/:#"):
        dibujar(linea)
        print()

    # Los acentos no deben alterar el cuerpo de la letra (filas 2-6)
    bases = {'á': 'a', 'é': 'e', 'ó': 'o', 'ú': 'u', 'ñ': 'n', 'ü': 'u'}
    for cp, (ch, g) in EXTRAS.items():
        if ch in bases:
            assert [c & 0x7C for c in g] == [c & 0x7C for c in ASCII[bases[ch]]], \
                "el acento de %s altera el cuerpo de la letra" % ch
    assert len(ASCII) == 95, len(ASCII)

    ruta = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'graficos', 'fuente5x7.c')
    os.makedirs(os.path.dirname(ruta), exist_ok=True)
    nombres = {'\\': 'barra invertida', "'": 'comilla', '*': 'asterisco', '/': 'barra'}
    with open(ruta, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/*\n * fuente5x7.c - GENERADO por tools/generar_fuente.py: no editar a mano.\n *\n'
                ' * Cada glifo son 5 columnas; el bit 0 de cada byte es la fila superior y se\n'
                ' * usan 7 filas (bits 0..6). ASCII 32..126 mas los caracteres del espanol\n'
                ' * (a e i o u con acento, n con tilde, u con dieresis, signos de apertura y grado).\n'
                ' * Los acentos ocupan las filas 0-1, libres en las minusculas.\n */\n')
        f.write('#include "graficos/fuente.h"\n\n')
        f.write('static const uint8_t ascii[95][FUENTE_COLUMNAS] = {\n')
        for i in range(32, 127):
            c = chr(i)
            etiqueta = nombres.get(c, c)
            f.write('    { %s },  /* %3d %s */\n' % (', '.join('0x%02X' % b for b in ASCII[c]), i, etiqueta))
        f.write('};\n\n')
        f.write('typedef struct {\n    uint16_t codigo;\n    uint8_t  columnas[FUENTE_COLUMNAS];\n} extra_t;\n\n')
        f.write('static const extra_t extras[] = {\n')
        for cp, (ch, g) in EXTRAS.items():
            f.write('    { 0x%04X, { %s } },\n' % (cp, ', '.join('0x%02X' % b for b in g)))
        f.write('};\n\n')
        f.write('const uint8_t *fuente_glifo(uint32_t codigo)\n{\n'
                '    if (codigo >= 32 && codigo <= 126) {\n        return ascii[codigo - 32];\n    }\n'
                '    for (unsigned i = 0; i < sizeof extras / sizeof extras[0]; i++) {\n'
                '        if (extras[i].codigo == codigo) {\n            return extras[i].columnas;\n        }\n    }\n'
                "    return ascii['?' - 32];\n}\n")
    print("Escrito %s  (95 ASCII + %d extras)" % (os.path.normpath(ruta), len(EXTRAS)))


main()
